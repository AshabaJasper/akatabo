// Generates lib/core/theme/tokens.g.dart from design/tokens.json.
//
//   dart run tool/gen_tokens.dart
//
// tokens.json is the single source for every colour, text style, spacing step, radius and
// component size. Screens read them through the theme; nothing is typed by hand.
// The JSON is walked by key; its shape is checked by the generator test.
// ignore_for_file: avoid_dynamic_calls
import 'dart:convert';
import 'dart:io';

import 'src/source_hash.dart';

const tokensPath = '../design/tokens.json';
const outputPath = 'lib/core/theme/tokens.g.dart';

String generateTokens(String jsonText) {
  final data = jsonDecode(jsonText) as Map<String, dynamic>;
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/gen_tokens.dart from design/tokens.json. Do not edit.')
    ..writeln('// source-hash: ${sourceHash(jsonText)}')
    ..writeln('// ignore_for_file: public_member_api_docs, lines_longer_than_80_chars')
    ..writeln()
    ..writeln("import 'dart:ui' show Color, FontWeight;")
    ..writeln();

  // ---- colours
  final colours = (data['color']['tokens'] as List).cast<Map<String, dynamic>>();
  b.writeln('/// Every colour token, one field each, for one theme.');
  b.writeln('class AkColorTokens {');
  b.writeln('  const AkColorTokens({');
  for (final c in colours) {
    b.writeln('    required this.${camel(c['name'] as String)},');
  }
  b.writeln('  });');
  for (final c in colours) {
    final usage = (c['usage'] as String? ?? '').replaceAll('\n', ' ');
    b
      ..writeln()
      ..writeln('  /// `${c['name']}`: $usage')
      ..writeln('  final Color ${camel(c['name'] as String)};');
  }
  b.writeln();
  b.writeln('  /// Token values by their design name, for lookups such as a category colour.');
  b.writeln('  Map<String, Color> get byName => {');
  for (final c in colours) {
    b.writeln("    '${c['name']}': ${camel(c['name'] as String)},");
  }
  b.writeln('  };');
  b.writeln();
  b.writeln('  AkColorTokens copyWith({');
  for (final c in colours) {
    b.writeln('    Color? ${camel(c['name'] as String)},');
  }
  b.writeln('  }) => AkColorTokens(');
  for (final c in colours) {
    final n = camel(c['name'] as String);
    b.writeln('    $n: $n ?? this.$n,');
  }
  b.writeln('  );');
  b.writeln();
  b.writeln(
    '  static AkColorTokens lerp(AkColorTokens a, AkColorTokens b, double t) => AkColorTokens(',
  );
  for (final c in colours) {
    final n = camel(c['name'] as String);
    b.writeln('    $n: Color.lerp(a.$n, b.$n, t)!,');
  }
  b.writeln('  );');
  b.writeln('}');
  b.writeln();
  for (final theme in ['light', 'dark']) {
    b.writeln('const ak${theme[0].toUpperCase()}${theme.substring(1)}Tokens = AkColorTokens(');
    for (final c in colours) {
      final hex = ((c['value'] as Map)[theme] as String).substring(1).toUpperCase();
      b.writeln('  ${camel(c['name'] as String)}: Color(0xFF$hex),');
    }
    b.writeln(');');
    b.writeln();
  }

  // ---- main-colour palettes
  final palettes = data['palettes'] as Map<String, dynamic>;
  final keys = (palettes['keys'] as List).cast<String>();
  b.writeln('/// One main colour from Settings > Appearance, for both themes.');
  b.writeln('class AkPalette {');
  b.writeln(
    '  const AkPalette({required this.id, required this.label, required this.light, required this.dark});',
  );
  b.writeln('  final String id;');
  b.writeln('  final String label;');
  b.writeln('  final Map<String, Color> light;');
  b.writeln('  final Map<String, Color> dark;');
  b.writeln('}');
  b.writeln();
  b.writeln('/// Palette keys, as token names. A palette replaces exactly these tokens.');
  b.writeln('const akPaletteKeys = <String>[${keys.map((k) => "'$k'").join(', ')}];');
  b.writeln();
  b.writeln('const akPalettes = <AkPalette>[');
  for (final p in (palettes['items'] as List).cast<Map<String, dynamic>>()) {
    final values = p['values'] as Map<String, dynamic>;
    String mapFor(String theme) => keys
        .map(
          (k) =>
              "'$k': Color(0xFF${((values[k] as Map)[theme] as String).substring(1).toUpperCase()})",
        )
        .join(', ');
    b.writeln(
      "  AkPalette(id: '${p['id']}', label: '${p['label']}', light: {${mapFor('light')}}, dark: {${mapFor('dark')}}),",
    );
  }
  b.writeln('];');
  b.writeln();

  // ---- type
  final families = (data['type']['families'] as Map).cast<String, String>();
  String familyName(String key) => families[key]!.split(',').first.replaceAll('"', '').trim();
  b.writeln('/// A text style token. Sizes are logical pixels at text scale 1.');
  b.writeln('class AkTextToken {');
  b.writeln('  const AkTextToken(this.family, this.size, this.lineHeight, this.weight);');
  b.writeln('  final String family;');
  b.writeln('  final double size;');
  b.writeln('  final double lineHeight;');
  b.writeln('  final FontWeight weight;');
  b.writeln('}');
  b.writeln();
  b.writeln('abstract final class AkTextTokens {');
  b.writeln("  static const display = '${familyName('display')}';");
  b.writeln("  static const sans = '${familyName('sans')}';");
  for (final g in (data['type']['groups'] as List).cast<Map<String, dynamic>>()) {
    final fam = g['family'] == 'display' ? 'display' : 'sans';
    for (final s in (g['styles'] as List).cast<Map<String, dynamic>>()) {
      final size = (s['fontSize'] as String).replaceAll('px', '');
      final lh = (s['lineHeight'] as String).replaceAll('px', '');
      b.writeln('  /// `${s['name']}`');
      b.writeln(
        '  static const ${camel(s['name'] as String)} = AkTextToken($fam, $size, $lh, FontWeight.w${s['fontWeight']});',
      );
    }
  }
  b.writeln('}');
  b.writeln();

  // ---- spacing, radius, size
  void numbers(String className, String section, String prefix, String doc) {
    b.writeln('/// $doc');
    b.writeln('abstract final class $className {');
    for (final t in (data[section]['tokens'] as List).cast<Map<String, dynamic>>()) {
      final name = (t['name'] as String).replaceFirst('$prefix-', '');
      final id = RegExp(r'^\d').hasMatch(name) ? 's$name' : camel(name);
      b.writeln('  /// `${t['name']}`: ${t['usage']}');
      b.writeln('  static const double $id = ${(t['value'] as String).replaceAll('px', '')};');
    }
    b.writeln('}');
    b.writeln();
  }

  numbers('AkSpace', 'spacing', 'space', 'Spacing steps.');
  numbers(
    'AkRadiusTokens',
    'radius',
    'radius',
    'Corner radii at the "Rounded" setting. Read them through AkMetrics, which applies the Corners setting.',
  );
  numbers('AkSize', 'size', 'size', 'Component sizes.');
  return b.toString();
}

Future<void> main() async {
  final source = File(tokensPath).readAsStringSync();
  File(outputPath)
    ..createSync(recursive: true)
    ..writeAsStringSync(generateTokens(source));
  final r = await Process.run('dart', ['format', outputPath], runInShell: true);
  stdout.write(r.stdout);
  stderr.write(r.stderr);
}
