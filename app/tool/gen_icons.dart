// Generates lib/core/icons/icon_registry.g.dart from the icon table in design/DESIGN_SYSTEM.md.
//
//   dart run tool/gen_icons.dart
//
// The table is the only place an icon is defined. AkIcon draws these shapes on the
// 24 by 24 grid with a 2px round stroke in the current text colour.
import 'dart:io';

import 'src/source_hash.dart';

const systemPath = '../design/DESIGN_SYSTEM.md';
const outputPath = 'lib/core/icons/icon_registry.g.dart';

final _row = RegExp(r'^\| (\w[\w-]*) \| ([^|]*) \| `(.+)` \|$', multiLine: true);
final _shape = RegExp(r'<(path|circle|rect)\s+([^>]*?)\s*/?>');
final _attr = RegExp(r'([\w-]+)="([^"]*)"');

class IconRow {
  IconRow(this.name, this.usedFor, this.shapes);
  final String name;
  final String usedFor;
  final List<String> shapes; // Dart constructor expressions
}

/// The icon table section of DESIGN_SYSTEM.md, which is what the hash covers.
String iconSection(String source) {
  // A checkout with Windows line endings must parse and hash the same as one with \n.
  final markdown = source.replaceAll('\r\n', '\n');
  final start = markdown.indexOf('## Iconography');
  final end = markdown.indexOf('\n## ', start + 3);
  return markdown.substring(start, end < 0 ? markdown.length : end);
}

List<IconRow> parseIcons(String markdown) {
  final rows = <IconRow>[];
  for (final m in _row.allMatches(iconSection(markdown))) {
    final name = m.group(1)!;
    if (name == 'name') continue;
    final shapes = <String>[];
    for (final s in _shape.allMatches(m.group(3)!)) {
      final a = {for (final x in _attr.allMatches(s.group(2)!)) x.group(1)!: x.group(2)!};
      String n(String k) => double.parse(a[k] ?? '0').toString();
      switch (s.group(1)) {
        case 'path':
          shapes.add("AkIconShape.path('${a['d']}')");
        case 'circle':
          shapes.add('AkIconShape.circle(${n('cx')}, ${n('cy')}, ${n('r')})');
        case 'rect':
          shapes.add(
            'AkIconShape.rect(${n('x')}, ${n('y')}, ${n('width')}, ${n('height')}, ${n('rx')})',
          );
      }
    }
    if (shapes.isEmpty) throw FormatException('Icon "$name" has no shapes');
    rows.add(IconRow(name, m.group(2)!.trim(), shapes));
  }
  return rows;
}

String generateIcons(String markdown) {
  final rows = parseIcons(markdown);
  final names = <String>{};
  for (final r in rows) {
    if (!names.add(r.name)) {
      throw FormatException('Icon "${r.name}" appears twice');
    }
  }
  final b = StringBuffer()
    ..writeln(
      '// GENERATED by tool/gen_icons.dart from the icon table in design/DESIGN_SYSTEM.md. Do not edit.',
    )
    ..writeln('// source-hash: ${sourceHash(iconSection(markdown))}')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln("import 'ak_icon_shape.dart';")
    ..writeln()
    ..writeln('/// Every icon in the design system, by its table name.')
    ..writeln('enum AkIcons {');
  for (final r in rows) {
    b
      ..writeln('  /// ${r.usedFor}')
      ..writeln('  ${camel(r.name)}(<AkIconShape>[${r.shapes.join(', ')}]),');
  }
  b
    ..writeln('  ;')
    ..writeln()
    ..writeln('  const AkIcons(this.shapes);')
    ..writeln()
    ..writeln('  /// Shapes on the 24 by 24 grid.')
    ..writeln('  final List<AkIconShape> shapes;')
    ..writeln()
    ..writeln(
      '  /// The icon stored in a category\'s `iconKey`, or [dots] when the key is unknown.',
    )
    ..writeln('  static AkIcons fromKey(String key) => _byKey[key] ?? AkIcons.dots;')
    ..writeln()
    ..writeln('  static final Map<String, AkIcons> _byKey = {');
  for (final r in rows) {
    b.writeln("    '${r.name}': AkIcons.${camel(r.name)},");
  }
  b
    ..writeln('  };')
    ..writeln()
    ..writeln('  /// The table name, as stored in `iconKey`.')
    ..writeln('  String get key => _keys[index];')
    ..writeln()
    ..writeln('  static const _keys = <String>[${rows.map((r) => "'${r.name}'").join(', ')}];')
    ..writeln('}');
  return b.toString();
}

Future<void> main() async {
  final source = File(systemPath).readAsStringSync();
  File(outputPath)
    ..createSync(recursive: true)
    ..writeAsStringSync(generateIcons(source));
  final r = await Process.run('dart', ['format', outputPath], runInShell: true);
  stdout.write(r.stdout);
  stderr.write(r.stderr);
}
